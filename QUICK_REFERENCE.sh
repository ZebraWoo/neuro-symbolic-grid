⚙️  参数配置
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  train_with_metrics.sh 主要参数:

  --batch-size N
    └─ 批次大小 (默认: 16)
    └─ 显存不足时减小 (8, 16, 32)

  --seq-len N
    └─ 序列长度，单位为分钟 (默认: 720 = 24小时)
    └─ 减小以降低显存需求 (360, 720, 1440)

  --num-epochs N
    └─ 训练轮数 (默认: 30)
    └─ 快速验证用5-10，完整训练用30-50

  --learning-rate LR
    └─ 学习率 (默认: 0.001)
    └─ 调整范围: 0.0001 - 0.01

  --device DEVICE
    └─ 计算设备 (默认: auto)
    └─ 选项: auto, cuda, cpu

  --hidden-dim N
    └─ 隐藏层维度 (默认: 128)

  --embedding-dim N
    └─ 嵌入向量维度 (默认: 64)

