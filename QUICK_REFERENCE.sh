📈 评估指标说明
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  ✓ AUC (Area Under Curve)
    范围: [0, 1] | 越高越好 (>0.7优秀)
    说明: 分类器区分能力的度量

  ✓ Precision (精确率)
    范围: [0, 1] | 越高越好
    说明: 预测正确的正样本比例

  ✓ Recall (召回率)
    范围: [0, 1] | 越高越好
    说明: 找出所有正样本的能力

  ✓ F1-Score
    范围: [0, 1] | 越高越好 (>0.7优秀)
    说明: Precision和Recall的调和均值

  ✓ Silhouette Score
    范围: [-1, 1] | 越接近1越好
    说明: 聚类紧密度和分离度
    > 0.5: 优秀 | 0.3-0.5: 中等 | < 0.3: 较差

  ✓ Proximity
    范围: [0, 1] | 高值=正常，低值=异常
    说明: 样本与动态原型的相似度，用于异常检测

